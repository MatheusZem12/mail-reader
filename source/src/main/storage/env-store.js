const { app } = require('electron');
const fs = require('fs');
const path = require('path');

// Writes the user's OAuth configuration to the machine's local .env file.
// The user pastes the Client IDs on the app's setup screen and this module
// persists it all locally — nothing is embedded in the code or sent to a server.
// To use it on another computer, just copy the .env (or paste the codes again).

const KEYS = {
  googleClientId: 'MAIL_READER_GOOGLE_CLIENT_ID',
  googleClientSecret: 'MAIL_READER_GOOGLE_CLIENT_SECRET',
  microsoftClientId: 'MAIL_READER_MICROSOFT_CLIENT_ID',
};

const HEADER = [
  '# Mail Reader OAuth configuration — generated by the app itself.',
  '# This file is local to your machine and is in .gitignore (never commit it).',
  '# To use it on another computer, copy this file there.',
];

function getEnvPath() {
  return path.join(app.getAppPath(), '.env');
}

function getConfig() {
  const config = {};
  for (const [field, key] of Object.entries(KEYS)) {
    config[field] = (process.env[key] || '').trim();
  }
  return config;
}

function saveConfig(config) {
  const envPath = getEnvPath();
  let lines = [];
  if (fs.existsSync(envPath)) {
    lines = fs.readFileSync(envPath, 'utf-8').split(/\r?\n/);
  } else {
    lines = [...HEADER, ''];
  }

  for (const [field, key] of Object.entries(KEYS)) {
    if (!(field in config)) continue;
    const value = String(config[field] || '').trim();
    process.env[key] = value; // applies at once, without restarting the app

    const newLine = `${key}=${value}`;
    const index = lines.findIndex((line) => line.trim().startsWith(`${key}=`));
    if (index >= 0) {
      lines[index] = newLine;
    } else {
      if (lines.length > 0 && lines[lines.length - 1].trim() === '') lines.pop();
      lines.push(newLine, '');
    }
  }

  fs.writeFileSync(envPath, lines.join('\n').replace(/\n*$/, '\n'));
}

module.exports = { getConfig, saveConfig };
